import type {Meta,StoryObj} from '@storybook/react-vite';
import {expect,userEvent,within,fireEvent} from 'storybook/test';
import {withLibraryTheme} from '../../../../storybook';
import {StereoTuner} from './StereoTuner';
const meta={title:'Math/Stereo/Components/Stereo Tuner',component:StereoTuner,decorators:[withLibraryTheme],parameters:{layout:'fullscreen'},args:{illusion:'ring'}} satisfies Meta<typeof StereoTuner>;
export default meta;type Story=StoryObj<typeof meta>;
export const YourSeat:Story={};
export const TuneAndReveal:Story={play:async({canvasElement})=>{
 const c=within(canvasElement),stage=canvasElement.querySelector('[data-period]')!;
 const initial=Number(stage.getAttribute('data-period'));
 await fireEvent.change(c.getByRole('slider',{name:'Sitting distance'}),{target:{value:'80'}});
 await expect(Number(stage.getAttribute('data-period'))).toBeGreaterThan(initial);
 await userEvent.click(c.getByRole('button',{name:'Cross-eyed'}));
 await expect(canvasElement.querySelector('.zen-dot-stereo')).toHaveAttribute('data-viewing','crossed');
 await userEvent.click(c.getByRole('button',{name:'I see one steady cross'}));
 const period=stage.getAttribute('data-period');
 await expect(c.getByRole('slider',{name:'Depth strength'})).toBeInTheDocument();
 await userEvent.click(c.getByRole('button',{name:'Keep this setting · reveal pattern'}));
 await expect(c.getByRole('img',{name:'Continuous hidden-depth stereogram'})).toBeInTheDocument();
 await expect(stage).toHaveAttribute('data-period',period!);
 await userEvent.keyboard('{Escape}');await expect(c.queryByRole('img',{name:'Continuous hidden-depth stereogram'})).not.toBeInTheDocument();
 await userEvent.click(c.getByRole('button',{name:'Return to the target'}));
 await userEvent.click(c.getByRole('button',{name:'Find the cross again'}));
 await expect(c.getByRole('img',{name:'Left eye alignment target'})).toBeInTheDocument();
}};
