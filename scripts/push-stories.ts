// Writes the Push area's scenario stories from the change's spec deltas: one stories file per
// capability (`src/library/push/screens/<Name>/<Name>.stories.tsx`), one `scenario()` story per
// scenario, with its name, When, Then, requirement and SHALL text as literals (story-spec reads
// them from the source without running anything). What each story does is hand-written beside it
// in `<Name>.plays.ts`, by the same export name. The stories own the spec once they exist
// (`story-spec sync`): a scenario is then added by hand in its stories file, and this script will
// not write over a stories file unless told to with `--force`.
//
//   npx tsx scripts/push-stories.ts [capability ...] [--from <specs dir>] [--force]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const args = process.argv.slice(2);
const fromAt = args.indexOf('--from');
const specs = fromAt >= 0 ? args[fromAt + 1] : 'openspec/specs';
const force = args.includes('--force');
const only = args.filter((a, i) => !a.startsWith('--') && (fromAt < 0 || i !== fromAt + 1));
const out = 'src/library/push/screens';

interface Scenario { name: string; when: string; then: string; given?: string; and: string[]; requirement: string; shall: string }

const pascal = (text: string) =>
  text
    .replace(/[’']/g, '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('')
    .replace(/^(\d)/, 'N$1');

function parse(markdown: string): { purpose: string; scenarios: Scenario[] } {
  const lines = markdown.split('\n');
  let purpose = '';
  const scenarios: Scenario[] = [];
  let section = '';
  let requirement = '';
  let shall: string[] = [];
  let current: Scenario | undefined;
  for (const raw of lines) {
    const line = raw.trimEnd();
    let m: RegExpExecArray | null;
    if ((m = /^## (.+)$/.exec(line))) { section = m[1]; continue; }
    if ((m = /^### Requirement: (.+)$/.exec(line))) { requirement = m[1].trim(); shall = []; current = undefined; continue; }
    if ((m = /^#### Scenario: (.+)$/.exec(line))) { current = { name: m[1].trim(), when: '', then: '', and: [], requirement, shall: shall.join(' ').trim() }; scenarios.push(current); continue; }
    if (current && (m = /^- \*\*(GIVEN|WHEN|THEN|AND)\*\*\s*(.*)$/.exec(line))) {
      const text = m[2].trim();
      if (m[1] === 'GIVEN') current.given = text;
      else if (m[1] === 'WHEN') current.when = text;
      else if (m[1] === 'THEN' && !current.then) current.then = text;
      else current.and.push(text);
      continue;
    }
    if (/^purpose$/i.test(section) && line) purpose += (purpose ? ' ' : '') + line;
    else if (requirement && !current && line) shall.push(line);
  }
  return { purpose, scenarios };
}

const q = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

for (const capability of readdirSync(specs).sort()) {
  if (!capability.startsWith('push-') || (only.length && !only.includes(capability))) continue;
  const { purpose, scenarios } = parse(readFileSync(join(specs, capability, 'spec.md'), 'utf8'));
  const name = pascal(capability.replace(/^push-/, ''));
  const title = capability.replace(/^push-/, '').split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
  const seen = new Set<string>();
  const stories = scenarios.map((s) => {
    let id = pascal(s.name);
    if (seen.has(id)) id = `${pascal(s.requirement).slice(0, 40)}${id}`;
    for (let n = 2; seen.has(id); n++) id = `${pascal(s.name)}${n}`;
    seen.add(id);
    return { id, ...s };
  });
  const body = `// Generated by scripts/push-stories.ts from the ${capability} spec: one story per scenario. The words are
// here, as literals, because story-spec reads them from this file; what each story does is in
// ${name}.plays.ts under the same name. Change a scenario's words here, then run
// \`story-spec sync --change push-3-surface\`.
import type { Meta, StoryObj } from '@storybook/react-vite';
import { scenario } from 'story-spec';
import { withLibraryTheme } from '../../../storybook';
import { withRenderer } from '../../../foundation/stories/story';
import { Emulator } from '../Emulator/Emulator';
import { scenarioStory } from '../scenario';
import { plays } from './${name}.plays';

const meta = {
  title: 'Push/Screens/${title}',
  component: Emulator,
  decorators: [withRenderer, withLibraryTheme],
  parameters: { layout: 'fullscreen', spec: { capability: ${q(capability)}, purpose: ${q(purpose)} } },
} satisfies Meta<typeof Emulator>;
export default meta;
type Story = StoryObj<typeof meta>;

${stories
  .map(
    (s) => `export const ${s.id}: Story = scenario(
  {
    name: ${q(s.name)},${s.given ? `\n    given: ${q(s.given)},` : ''}
    when: ${q(s.when)},
    then: ${q(s.then)},${s.and.length ? `\n    and: [${s.and.map(q).join(', ')}],` : ''}
    requirement: ${q(s.requirement)},
    shall: ${q(s.shall)},
    act: plays.${s.id}.act,
    check: plays.${s.id}.check,
  },
  scenarioStory(plays.${s.id}),
);`,
  )
  .join('\n\n')}
`;
  const storiesFile = join(out, name, `${name}.stories.tsx`);
  if (existsSync(storiesFile) && !force) {
    console.log(`${capability}: ${name}/${name}.stories.tsx exists and owns its scenarios; not written (add a scenario there by hand, or pass --force to write it again from ${specs})`);
    continue;
  }
  mkdirSync(join(out, name), { recursive: true });
  writeFileSync(storiesFile, body);
  const playsFile = join(out, name, `${name}.plays.ts`);
  const have = existsSync(playsFile) ? readFileSync(playsFile, 'utf8') : '';
  const missing = stories.filter((s) => !new RegExp(`^  ${s.id}:`, 'm').test(have));
  console.log(`${capability}: ${stories.length} stories in ${name}/${name}.stories.tsx${missing.length ? `; ${missing.length} plays to write: ${missing.map((s) => s.id).join(', ')}` : ''}`);
}
