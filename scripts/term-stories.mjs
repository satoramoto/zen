import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = process.env.MATH_PREVIEW_URL ?? 'http://127.0.0.1:6027';
await mkdir('.shots/terms', {recursive:true});
const browser = await chromium.launch({headless:true});
try {
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror', e=>errors.push(e.message));
 await page.goto(`${base}/iframe.html?id=math-calculator-components-wave-calculator--function-composition&viewMode=story&globals=theme:linear;mode:dark`);
 await page.waitForFunction(()=>[...document.querySelectorAll('.zen-equation-input')].every(e=>e.dataset.ready==='true'));
 const field=page.locator('math-field').first();
 await field.locator('[data-zen-math-token="parameter"]').first().click();
 await page.waitForFunction(()=>document.activeElement?.tagName==='MATH-FIELD');
 await page.keyboard.press('Control+a');
 await page.getByLabel('Explore equation parts', {exact:true}).waitFor();
 await page.getByRole('button',{name:'Select sin function, part 3',exact:true}).click();
 await page.getByRole('button',{name:'Half as large',exact:true}).focus();
 await page.getByText('– – proposal · not applied').waitFor();
 assert.equal(await page.getByLabel('f at probe').textContent(),'1.000');
 assert.equal(await page.locator('.zen-calculator__curve[style*="stroke-dasharray"]').count(),3);
 await page.screenshot({path:'.shots/terms/desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Apply change',exact:true}).click();
 assert.equal(await page.getByLabel('f at probe').textContent(),'0.500');
 await page.getByRole('button',{name:'Undo transformation',exact:true}).click();
 await page.getByRole('button',{name:'Plain text',exact:true}).first().click();
 await page.getByRole('textbox',{name:'f(x) expression'}).fill('sin(x)+sin(x)');
 await page.getByRole('button',{name:'Explore parts of f',exact:true}).click();
 await page.getByRole('button',{name:'Select sin function, part 4',exact:true}).click();
 await page.getByRole('button',{name:'Flip its sign',exact:true}).click();
 assert.equal(await page.getByLabel('f at probe').textContent(),'2.000');
 await page.getByRole('button',{name:'Apply change',exact:true}).click();
 assert.equal(await page.getByLabel('f at probe').textContent(),'0.000');
 await page.getByRole('textbox',{name:'f(x) expression'}).fill('sin(x)');
 assert.equal(await page.getByRole('button',{name:'Undo transformation',exact:true}).count(),0);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Explore parts of f',exact:true}).click();
 await page.getByRole('button',{name:'Shift right',exact:true}).click();
 await page.screenshot({path:'.shots/terms/narrow.png',fullPage:true});
 await page.getByRole('button',{name:'View proposal on graph ↓',exact:true}).click();
 assert.ok(await page.locator('.zen-calculator__plot').evaluate(el=>el.getBoundingClientRect().top<innerHeight));
 await page.getByRole('button',{name:'Back to selected part ↑',exact:true}).click();
 await page.getByRole('button',{name:'Close equation exploration',exact:true}).click();
 await page.getByRole('button',{name:'Typeset',exact:true}).first().click();
 await page.goto(`${base}/iframe.html?id=math-calculator-components-wave-calculator--function-composition&viewMode=story&globals=theme:linear;mode:light`);
 await page.getByRole('button',{name:'Explore parts of f',exact:true}).click();
 await page.getByRole('button',{name:'Twice as large',exact:true}).click();
 await page.screenshot({path:'.shots/terms/light.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 console.log('PASS native math selection, focus preview, apply/undo, repeated terms, edit invalidation, narrow layout');
} finally {await browser.close();}
